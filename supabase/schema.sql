-- 1. Profiles Table (Holds all user details visible to the project owner)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text,
  phone text,
  nickname text default 'Trader',
  display_name text,
  avatar text default '/static/user/profile.png',
  balance numeric(12, 2) default 0.00,
  total_balance numeric(12, 2) default 0.00,
  reward_total numeric(12, 2) default 0.00,
  pending numeric(12, 2) default 0.00,
  points integer default 0,
  vip_level integer default 1,
  invite_code text default 'LP8899',
  is_pin_set boolean default false,
  role text default 'user',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS on profiles
alter table public.profiles enable row level security;

-- Policies for profiles
create policy "Allow public read of profiles"
  on public.profiles for select
  using (true);

create policy "Users can insert their own profile"
  on public.profiles for insert
  with check (auth.uid() = id);

create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id);

-- 2. Wallets Table (Payout & Receiving Wallets bound to users)
create table if not exists public.wallets (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null,
  ct_type integer not null default 3,
  ct_name text not null default 'PhonePe',
  account text not null,
  name text,
  phone text,
  status integer default 1,
  min_amount numeric(10, 2) default 500.00,
  max_amount numeric(10, 2) default 25000.00,
  daily_limit numeric(12, 2) default 100000.00,
  today_turnover numeric(12, 2) default 0.00,
  today_count integer default 0,
  success_rate numeric(5, 2) default 100.00,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.wallets enable row level security;

create policy "Users can view their own wallets"
  on public.wallets for select
  using (auth.uid() = user_id);

create policy "Users can insert their own wallets"
  on public.wallets for insert
  with check (auth.uid() = user_id);

create policy "Users can update their own wallets"
  on public.wallets for update
  using (auth.uid() = user_id);

-- 3. Deposits Table (UPI Deposit Records)
create table if not exists public.deposits (
  id text primary key,
  user_id uuid references auth.users on delete cascade not null,
  amount numeric(10, 2) not null,
  qr_id integer,
  vpa text,
  utr text not null,
  status text default 'pending', -- pending, completed, rejected
  source text default 'upi',
  verified_by text,
  verified_at timestamp with time zone,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.deposits enable row level security;

create policy "Users can view their own deposits"
  on public.deposits for select
  using (auth.uid() = user_id);

create policy "Users can submit deposits"
  on public.deposits for insert
  with check (auth.uid() = user_id);

-- 4. Automatic User Profile Creation Trigger
-- When a new user registers in Supabase Auth, automatically insert/update public.profiles
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (
    id,
    email,
    phone,
    nickname,
    display_name,
    invite_code,
    vip_level,
    balance
  )
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'phone', ''),
    coalesce(new.raw_user_meta_data->>'nickname', 'Trader'),
    coalesce(new.raw_user_meta_data->>'nickname', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'inviteCode', 'LP8899'),
    coalesce((new.raw_user_meta_data->>'vipLevel')::integer, 1),
    coalesce((new.raw_user_meta_data->>'balance')::numeric, 0.00)
  )
  on conflict (id) do update set
    email = excluded.email,
    phone = coalesce(excluded.phone, profiles.phone),
    nickname = coalesce(excluded.nickname, profiles.nickname),
    updated_at = now();
  return new;
end;
$$ language plpgsql security definer;

-- Trigger execution on auth.users insert
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
